const { open, ACCTS } = require('./lib.cjs');
const { execSync } = require('child_process');
const V = require('./vault.json').vault;
const cast = (who, sig, ...a) => execSync(`~/.foundry/bin/cast send --unlocked --from ${ACCTS[who]} --rpc-url http://127.0.0.1:8545 ${V} "${sig}" ${a.join(' ')}`, { stdio: 'pipe' });
const shot = async (p, n) => { await p.waitForTimeout(400); await p.screenshot({ path: `s/RV-${n}.png`, fullPage: true }); };
(async () => {
  const { b, page: p } = await open('buyer');
  const { page: s } = await open('supplier', { browser: b });
  await p.goto('http://localhost:8791/new'); await p.waitForTimeout(1200);
  await p.fill('input[autocomplete=organization]', 'Phoenix Store');
  await p.locator('section label.field input').nth(1).fill('Samsung Galaxy S10 phones');
  const q = p.locator('.qty-row input'); await q.nth(0).fill('10'); await q.nth(1).fill('2.50');
  await p.locator('.detail-row input').nth(0).fill('128 GB storage, dual SIM');
  await p.locator('.detail-row input').nth(1).fill('6.1-inch screen');
  await p.click('button:has-text("1 month")'); await p.waitForTimeout(1200);
  await p.click('button:has-text("Next")'); await p.waitForTimeout(600);
  await p.click('button:has-text("Create the link")'); await p.waitForTimeout(1200);
  const link = await p.inputValue('input[readonly]');
  await s.goto(link); await s.waitForTimeout(1500);
  await s.click('button.money:has-text("gree")'); await s.waitForTimeout(4000);
  await p.click('button:has-text("Next")'); await p.waitForTimeout(1500);
  await p.click('button.money:has-text("Lock $25.00")');
  await p.waitForURL(/\/o\/[A-Za-z0-9]{10}/, { timeout: 40000 }); await p.waitForTimeout(1500);
  const url = p.url().split('?')[0];
  cast('supplier', 'accept(uint256)', 1);
  cast('supplier', 'markShipped(uint256,bytes32)', 1, '0x' + '11'.repeat(32));
  cast('buyer', 'confirmArrival(uint256)', 1);
  cast('buyer', 'release(uint256)', 1);
  await p.goto(url); await p.waitForTimeout(2500);
  await shot(p, '1-buyer-ask');
  const yn = p.locator('.review-ask .yn');
  console.log('buyer questions:', await yn.count());
  await yn.nth(0).locator('button:has-text("Yes")').click();
  await yn.nth(1).locator('button:has-text("Yes")').click();
  await yn.nth(2).locator('button:has-text("Yes")').click();
  await p.fill('.review-ask textarea', 'Shipped two days early, phones exactly as described.');
  await p.click('button:has-text("Sign and post review")'); await p.waitForTimeout(2000);
  await shot(p, '2-buyer-sent');
  // the supplier can't see the buyer's review yet
  const peek = await (await fetch('http://localhost:8791/api/orders/' + url.split('/o/')[1] + '/reviews')).json();
  console.log('before supplier: revealed', peek.revealed, 'reviews keys', Object.keys(peek.reviews));
  await s.goto(url); await s.waitForTimeout(2500);
  await shot(s, '3-supplier-ask');
  const sy = s.locator('.review-ask .yn');
  await sy.nth(0).locator('button:has-text("Yes")').click();
  await sy.nth(1).locator('button:has-text("Yes")').click();
  await sy.nth(2).locator('button:has-text("Yes")').click();
  await s.click('button:has-text("Sign and post review")'); await s.waitForTimeout(2000);
  await shot(s, '4-revealed');
  const sum = await (await fetch(`http://localhost:8791/api/reviews/${ACCTS.supplier}`)).json();
  console.log('supplier summary', JSON.stringify(sum.asSupplier));
  // a new order with this supplier shows the reviews in the track record
  await p.goto('http://localhost:8791/new'); await p.waitForTimeout(1000);
  await b.close();
})().catch((e) => { console.log('FAIL', e.message); process.exit(1); });
